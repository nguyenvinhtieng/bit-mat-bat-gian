export type TKey = keyof (typeof dict)['vi'];

const initial = (): Lang => {
  const saved = localStorage.getItem(KEY);
  if (saved === 'vi' || saved === 'en') return saved;
  return navigator.language?.toLowerCase().startsWith('vi') ? 'vi' : 'en';
};

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: initial(),
  setLang: (lang) => {
    localStorage.setItem(KEY, lang);
    set({ lang });
  },
}));

/** Hook returning a translate function; re-renders on language change.
 * `{killer}` / `{killerEn}` (plural in English), `{seg}`, `{Seg}` and `{deadline}` come from the current room's map skin. */
export function useT() {
  const lang = useLang((s) => s.lang);
  const skin = mapSkin(useStore((s) => s.room?.mapSlug));
  return (k: TKey) => {
    const seg = skin.labels.segment[lang];
    const vars: Record<string, string> = {
      killer: skin.killerName.vi,
      killerEn: plural(skin.killerName.en),
      seg,
      Seg: seg[0].toUpperCase() + seg.slice(1),
      deadline: skin.labels.deadline[lang],
    };
    return dict[lang][k].replace(/\{(\w+)\}/g, (m, v: string) => vars[v] ?? m);
  };
}

const plural = (w: string) => (w.endsWith('s') ? w : `${w}s`);
