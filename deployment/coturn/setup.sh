#!/usr/bin/env bash
# TURN relay (coturn) for voice chat, on the same VPS as the game server.
# Needed when STUN alone fails: 3G/4G carrier NAT, office firewalls that block UDP.
#
# Usage (from repo on VPS):
#   sudo bash deployment/coturn/setup.sh
#   sudo TURN_DOMAIN=turn.vinhtieng.com bash deployment/coturn/setup.sh   # + TLS (turns:) on 443
#
# TURN_DOMAIN is optional: a DNS-only record (grey cloud — Cloudflare cannot proxy TURN) pointing at
# this VPS. With it, a Let's Encrypt cert enables TURN-over-TLS on 443, which passes the strictest
# office proxies. Without it, plain TURN over UDP/TCP 3478 and TCP 443 still covers most networks.
#
# AWS: also open these in the instance's Security Group (ufw alone is not enough):
#   UDP 3478, TCP 3478, TCP 443, UDP 49152-65535
#
# Re-running is safe: the shared secret already in .env is kept.
set -euo pipefail

PUBLIC_IP="${PUBLIC_IP:-3.106.54.104}"
TURN_DOMAIN="${TURN_DOMAIN:-}"
APP_DIR="${APP_DIR:-/var/www/giao-keo}"
REALM="${REALM:-giaokeo.vinhtieng.com}"
MIN_PORT=49152
MAX_PORT=65535

if [[ "${EUID:-0}" -ne 0 ]]; then
  echo "Run as root: sudo bash $0"
  exit 1
fi

export DEBIAN_FRONTEND=noninteractive
ENV_FILE="${APP_DIR}/.env"

echo "==> Packages"
apt-get update -y
apt-get install -y coturn openssl

# AWS / NAT'd hosts: the NIC has a private address, coturn must advertise the public one
PRIVATE_IP="$(ip -4 route get 1.1.1.1 | awk '{for (i = 1; i < NF; i++) if ($i == "src") print $(i + 1)}')"
if [[ -n "${PRIVATE_IP}" && "${PRIVATE_IP}" != "${PUBLIC_IP}" ]]; then
  EXTERNAL_IP="${PUBLIC_IP}/${PRIVATE_IP}"
else
  EXTERNAL_IP="${PUBLIC_IP}"
fi
echo "    external-ip=${EXTERNAL_IP}"

echo "==> Shared secret (${ENV_FILE})"
touch "${ENV_FILE}"
SECRET="$(grep -E '^TURN_SECRET=' "${ENV_FILE}" | tail -1 | cut -d= -f2- || true)"
if [[ -z "${SECRET}" ]]; then
  SECRET="$(openssl rand -hex 32)"
  echo "TURN_SECRET=${SECRET}" >>"${ENV_FILE}"
fi
sed -i '/^TURN_HOST=/d;/^TURN_TLS_HOST=/d' "${ENV_FILE}"
echo "TURN_HOST=${TURN_DOMAIN:-${PUBLIC_IP}}" >>"${ENV_FILE}"
[[ -n "${TURN_DOMAIN}" ]] && echo "TURN_TLS_HOST=${TURN_DOMAIN}" >>"${ENV_FILE}"
chown --reference="${APP_DIR}" "${ENV_FILE}"
chmod 600 "${ENV_FILE}"

TLS_CONF="no-tls
no-dtls"
if [[ -n "${TURN_DOMAIN}" ]]; then
  echo "==> TLS cert for ${TURN_DOMAIN} (nginx on :80 answers the challenge)"
  apt-get install -y certbot python3-certbot-nginx
  certbot certonly --nginx -d "${TURN_DOMAIN}" --non-interactive --agree-tos --register-unsafely-without-email
  # coturn runs as 'turnserver' and cannot read /etc/letsencrypt/live: copy on every renewal
  HOOK=/etc/letsencrypt/renewal-hooks/deploy/coturn.sh
  cat >"${HOOK}" <<EOF
#!/bin/sh
install -d -o turnserver -g turnserver -m 750 /etc/coturn
install -o turnserver -g turnserver -m 640 /etc/letsencrypt/live/${TURN_DOMAIN}/fullchain.pem /etc/coturn/fullchain.pem
install -o turnserver -g turnserver -m 640 /etc/letsencrypt/live/${TURN_DOMAIN}/privkey.pem /etc/coturn/privkey.pem
systemctl restart coturn 2>/dev/null || true
EOF
  chmod +x "${HOOK}"
  "${HOOK}"
  TLS_CONF="cert=/etc/coturn/fullchain.pem
pkey=/etc/coturn/privkey.pem
no-dtls"
fi

echo "==> /etc/turnserver.conf"
cat >/etc/turnserver.conf <<EOF
# generated by deployment/coturn/setup.sh — edit the script, not this file
listening-port=3478
# 443 is free here (TLS ends at Cloudflare, nginx only listens on 80); it takes plain TCP and TLS
tls-listening-port=443
external-ip=${EXTERNAL_IP}
min-port=${MIN_PORT}
max-port=${MAX_PORT}
realm=${REALM}
use-auth-secret
static-auth-secret=${SECRET}
fingerprint
${TLS_CONF}
no-cli
no-multicast-peers
# never relay into this host's private networks (AWS metadata 169.254.169.254 included)
denied-peer-ip=0.0.0.0-0.255.255.255
denied-peer-ip=10.0.0.0-10.255.255.255
denied-peer-ip=100.64.0.0-100.127.255.255
denied-peer-ip=127.0.0.0-127.255.255.255
denied-peer-ip=169.254.0.0-169.254.255.255
denied-peer-ip=172.16.0.0-172.31.255.255
denied-peer-ip=192.168.0.0-192.168.255.255
# one allocation per relayed peer connection (mesh: up to 9 per player); the 16k relay ports cap it anyway
total-quota=4000
bps-capacity=0
stale-nonce=600
log-file=syslog
simple-log
EOF

# Ubuntu's unit runs as 'turnserver': allow binding :443
mkdir -p /etc/systemd/system/coturn.service.d
cat >/etc/systemd/system/coturn.service.d/override.conf <<EOF
[Service]
AmbientCapabilities=CAP_NET_BIND_SERVICE
EOF
[[ -f /etc/default/coturn ]] && sed -i 's/^#\?TURNSERVER_ENABLED=.*/TURNSERVER_ENABLED=1/' /etc/default/coturn

echo "==> Firewall (UFW)"
ufw allow 3478/udp
ufw allow 3478/tcp
ufw allow 443/tcp
ufw allow "${MIN_PORT}:${MAX_PORT}/udp"

systemctl daemon-reload
systemctl enable coturn
systemctl restart coturn
sleep 1
systemctl --no-pager --lines=5 status coturn || true

cat <<EOF

coturn is up (${PUBLIC_IP}).

Next:
  1. AWS Security Group inbound: UDP 3478, TCP 3478, TCP 443, UDP ${MIN_PORT}-${MAX_PORT}
  2. Reload the game server so it picks up TURN_* from ${ENV_FILE}:
       sudo -u deploy bash ${APP_DIR}/deployment/deploy.sh
  3. Check: https://${REALM}/ice should list turn: URLs
     Test relay: https://webrtc.github.io/samples/src/content/peerconnection/trickle-ice/
     (paste a turn: URL + username/credential from /ice, expect "relay" candidates)
  Logs: journalctl -u coturn -f
EOF
