/**
 * Measures each Sài Gòn prop's ground footprint from its sprite in maps/game/atlas/decor-0 and writes
 * packages/shared/src/maps/game/collision.ts (the movement blockers). Re-run after moving props or repainting art:
 *   tsx tools/paint/sg-footprints.ts
 * Footprint = opaque width of the sprite's bottom band (ignores wires, awnings, umbrellas up top),
 * a depth proportional to that width, clipped to the furniture slots it stands on — so a prop never
 * blocks more than its slot did, and every station stays reachable.
 */
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { FURNITURE_SLOTS } from '../../packages/shared/src/layout';
import { TILE } from '../../packages/shared/src/constants';
import { GAME_PROPS } from '../../packages/shared/src/maps/game/props';

const ROOT = path.resolve(import.meta.dirname, '../..');
const ATLAS = path.join(ROOT, 'apps/web/public/assets/maps/game/atlas/decor-0');
const OUT = path.join(ROOT, 'packages/shared/src/maps/game/collision.ts');

const ALPHA = 128; // ignore soft shadows / anti-aliasing
const BAND = 0.15; // bottom share of the visible height that touches the ground
const DEPTH_K = 0.45; // footprint depth ≈ 0.45 × width (3/4 view)
const DEPTH_MIN = 10;
const DEPTH_MAX = 36;

type Frame = { frame: { x: number; y: number; w: number; h: number } };
const meta = JSON.parse(fs.readFileSync(`${ATLAS}.json`, 'utf8')) as { frames: Record<string, Frame>; meta: { textureScale?: number } };
const texScale = Number(meta.meta.textureScale) || 1;
const { data, info } = await sharp(`${ATLAS}.webp`).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const alpha = (x: number, y: number) => data[(y * info.width + x) * 4 + 3];

/** footprint in frame px: [left, right, bottom] of the bottom band */
function measure(key: string) {
  const f = meta.frames[key].frame;
  let y0 = -1, y1 = -1;
  for (let y = 0; y < f.h; y++)
    for (let x = 0; x < f.w; x++)
      if (alpha(f.x + x, f.y + y) >= ALPHA) {
        if (y0 < 0) y0 = y;
        y1 = y;
        break;
      }
  const top = Math.round(y1 - (y1 - y0) * BAND);
  let l = f.w, r = -1;
  for (let y = top; y <= y1; y++)
    for (let x = 0; x < f.w; x++)
      if (alpha(f.x + x, f.y + y) >= ALPHA) {
        l = Math.min(l, x);
        r = Math.max(r, x);
      }
  return { w: f.w, h: f.h, l, r: r + 1, bottom: y1 + 1 };
}

const GAP = 40; // stacked copies of one prop (hẻm barriers, one per tile) join into one continuous fence
const slots = Object.values(FURNITURE_SLOTS).map(([x, y, w, h]) => [x * TILE, y * TILE, (x + w) * TILE, (y + h) * TILE]);
const boxes: { key: string; at: string; box: number[] }[] = [];
const cache = new Map<string, ReturnType<typeof measure>>();
for (const p of GAME_PROPS) {
  if (p.wall || !meta.frames[p.key]) continue;
  const m = cache.get(p.key) ?? measure(p.key);
  cache.set(p.key, m);
  const s = (p.scale ?? 1) / texScale;
  const seatedGroup = p.key === 'prop-coordination-danh-bai';
  const l = seatedGroup ? p.x - 90 * (p.scale ?? 1) : p.x + (m.l - m.w / 2) * s;
  const r = seatedGroup ? p.x + 90 * (p.scale ?? 1) : p.x + (m.r - m.w / 2) * s;
  const b = p.y - (m.h - m.bottom) * s;
  // This floor vignette contains four seated people, not one upright prop.
  // Reserve its mat depth so players cannot walk through the northern players.
  const depth = seatedGroup ? 112 * (p.scale ?? 1)
    : Math.min(DEPTH_MAX, Math.max(DEPTH_MIN, (r - l) * DEPTH_K));
  const t = b - depth;
  for (const [sl, st, sr, sb] of slots) {
    const box = [Math.max(l, sl), Math.max(t, st), Math.min(r, sr), Math.min(b, sb)].map(Math.round);
    if (box[2] - box[0] < 2 || box[3] - box[1] < 2) continue;
    const prev = boxes.find((o) => o.key === p.key && o.box[0] === box[0] && o.box[2] === box[2] && box[1] - o.box[3] <= GAP && box[1] >= o.box[1]);
    if (prev) prev.box[3] = Math.max(prev.box[3], box[3]);
    else boxes.push({ key: p.key, at: `${(p.x / TILE).toFixed(1)},${(p.y / TILE).toFixed(1)}`, box });
  }
}
const rows = boxes.map((o) => `  [${o.box.join(', ')}], // ${o.key} @${o.at}`);

fs.writeFileSync(
  OUT,
  `import type { PxBox } from '../../layout';

/** Generated by tools/paint/sg-footprints.ts — do not edit by hand. Prop footprints that block movement (px). */
export const GAME_COLLISION: PxBox[] = [
${rows.join('\n')}
];
`,
);
console.log(`${rows.length} boxes -> ${path.relative(ROOT, OUT)}`);
